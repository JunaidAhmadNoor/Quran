// Pure transform from the upstream editions (one JSON file per book and language) to the files in
// generated/: a meta file per book and one file per chapter with Arabic, English and Urdu joined by
// hadith number. Texts are copied verbatim (only surrounding whitespace is trimmed).
import { createHash } from 'node:crypto';
import type { BookId, BookMeta, HadithRecord, SectionFile } from './types';

export interface Edition {
  metadata: {
    name: string;
    sections: Record<string, string>;
    section_details: Record<string, { hadithnumber_first: number; hadithnumber_last: number }>;
  };
  hadiths: { hadithnumber: number; text: string; reference: { book: number; hadith: number } }[];
}

export type Language = 'ara' | 'eng' | 'urd';

const json = (value: unknown) => `${JSON.stringify(value)}\n`;

/** Builds every generated file for one book. Paths are relative to generated/. */
export function buildBook(book: BookId, editions: Record<Language, Edition>): Map<string, string> {
  const { ara, eng, urd } = editions;
  const byNumber = (e: Edition) => new Map(e.hadiths.map((h) => [h.hadithnumber, h]));
  const [arMap, enMap, urMap] = [byNumber(ara), byNumber(eng), byNumber(urd)];

  const files = new Map<string, string>();
  const sections: BookMeta['sections'] = [];
  let hadithCount = 0;

  // Chapters come from the upstream ranges. A few Sahih Muslim ranges overlap their neighbours
  // (books 16, 36 and 43 start too early), so a chapter that starts before the previous one ends
  // starts right after it. Per-hadith references are not used: some are 0 or point elsewhere.
  const ranges = Object.entries(eng.metadata.section_details)
    .map(([key, r]) => ({ n: Number(key), first: r.hadithnumber_first, last: r.hadithnumber_last }))
    .sort((a, b) => a.n - b.n);
  let end = 0;
  for (const r of ranges) {
    if (r.last < 1) continue;
    if (r.first <= end) r.first = end + 1;
    end = Math.max(end, r.last);
  }
  const chapterOf = (n: number) => ranges.find((r) => n >= r.first && n <= r.last)?.n;

  const byChapter = new Map<number, HadithRecord[]>();
  for (const h of [...eng.hadiths].sort((a, b) => a.hadithnumber - b.hadithnumber)) {
    if (h.hadithnumber < 1) continue; // Muslim's Urdu edition has a non-hadith preface at 0
    const chapter = chapterOf(h.hadithnumber);
    if (chapter === undefined) continue;
    const record: HadithRecord = {
      n: h.hadithnumber,
      ref: [h.reference.book, h.reference.hadith],
      ar: arMap.get(h.hadithnumber)?.text.trim() ?? '',
      en: enMap.get(h.hadithnumber)?.text.trim() ?? '',
      ur: urMap.get(h.hadithnumber)?.text.trim() ?? '',
    };
    // Upstream keeps empty placeholders where a numbering scheme has no hadith.
    if (!record.ar && !record.en && !record.ur) continue;
    byChapter.set(chapter, [...(byChapter.get(chapter) ?? []), record]);
  }

  for (const [n, hadiths] of [...byChapter].sort((a, b) => a[0] - b[0])) {
    const key = String(n);
    const named = eng.metadata.sections[key]?.trim() ?? '';
    const title = named !== '' ? named : n === 0 ? 'Introduction' : `Book ${key}`;
    sections.push({
      n,
      title,
      first: hadiths[0]?.n ?? 0,
      last: hadiths.at(-1)?.n ?? 0,
      count: hadiths.length,
    });
    hadithCount += hadiths.length;
    files.set(`${book}/${key}.json`, json({ book, section: n, hadiths } satisfies SectionFile));
  }

  const meta: BookMeta = { id: book, hadithCount, sections };
  files.set(`${book}/meta.json`, json(meta));
  return files;
}

/** generated/loaders.ts: one dynamic import per chapter, so a chapter loads only when read. */
export function buildLoaders(paths: string[]): string {
  const entries = paths
    .filter((p) => !p.endsWith('meta.json'))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
    .map(
      (p) => `  '${p.replace(/\.json$/, '')}': () => import('./${p}', { with: { type: 'json' } }),`,
    );
  return `// Generated by scripts/generate.ts. Do not edit.\n/* eslint-disable */\nexport const loaders: Record<string, () => Promise<{ default: unknown }>> = {\n${entries.join('\n')}\n};\n`;
}

export const sha256 = (content: string | Buffer) =>
  createHash('sha256').update(content).digest('hex');
